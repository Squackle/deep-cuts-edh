import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {LEVELS,BASE_LEVELS,GALAXIES,CHAPTERS} from "../src/levels.js";
import {AUDIT_VERSION,structuralAudit,auditLegalRoutes,auditCsv,boardFingerprint} from "../src/readiness-audit.js";
const read=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8");
test("500-vault structure inventory preserves original stage IDs, stable families and ten galaxy rollups",()=>{
 const report=structuralAudit();
 assert.equal(AUDIT_VERSION,1);
 assert.equal(report.version,1);
 assert.equal(report.format,"mana-heist-readiness-audit");
 assert.equal(report.summary.scoredVaults,500);
 assert.equal(report.summary.galaxies,10);
 assert.equal(report.summary.worlds,50);
 assert.equal(report.rows.length,LEVELS.length);
 assert.equal(report.galaxies.length,GALAXIES.length);
 assert.equal(CHAPTERS.length,50);
 assert.equal(report.summary.originalAuthored,BASE_LEVELS.length);
 assert.equal(report.summary.templateVariants,LEVELS.filter(p=>p.templateId).length);
 assert.equal(report.rows[0].id,LEVELS[0].id);
 assert.equal(report.rows.at(-1).id,LEVELS.at(-1).id);
 assert.deepEqual(report.galaxies.map(g=>g.stages),Array(10).fill(50));
 assert.ok(report.summary.repeatedFamilyCandidates>0,"generated stage families require review");
 assert.ok(report.rows.every(r=>r.flags.every(f=>["SIMILAR_BOARD","REPEATED_FAMILY","INHERITED_TEMPLATE_ROUTE","MISSING_LEGAL_REFERENCE","PROOF_INCONCLUSIVE"].includes(f))));
 assert.ok(report.rows.every(r=>r.humanCurriculumReview==="not-performed"));
 assert.ok(report.rows.every(r=>r.physicalDeviceReview==="not-performed"));
 assert.ok(report.rows.every(r=>r.empiricalDifficulty==="not-measured"));
 assert.equal(report.summary.humanCurriculumReviewed,0);
 assert.equal(report.summary.physicalDeviceReviewed,0);
 assert.equal(report.summary.empiricalDifficultySamples,0);
 assert.match(report.caveat,/NOT proof/);
});
test("board similarity ignores titles, preserves actual mana/card symbols and not labeled strategy uniqueness",()=>{
 const before=structuredClone(LEVELS[0]);
 const after=structuredClone(before);
 after.title="Cosmetic title changed";after.briefing="Text changed";
 assert.equal(boardFingerprint(before),boardFingerprint(after),"renaming alone is not a new board");
 after.stages[0].cost={B:2,U:4};
 assert.notEqual(boardFingerprint(before),boardFingerprint(after),"mana rules structure must influence similarity");
 assert.notEqual(boardFingerprint(LEVELS[0]),boardFingerprint(LEVELS.at(-1)));
});
test("offline reference audit has legal replays for all 500 current puzzles, distinct from optimization and human QA", {timeout:150000},()=>{
 const report=auditLegalRoutes(LEVELS);
 assert.equal(report.summary.scoredVaults,500);
 const problems=report.rows.filter(r=>r.proofStatus!=="legal-replay");
 assert.deepEqual(problems.map(r=>({id:r.id,status:r.proofStatus,error:r.proofError})),[],
  "Every scored puzzle needs a complete reducer legal route or explicit unresolved status");
 assert.equal(report.summary.legalReferenceReplays,500);
 assert.equal(report.summary.failedReferenceReplays,0);
 assert.equal(report.summary.inconclusiveReferenceReplays,0);
 assert.equal(report.summary.uncheckedReferenceReplays,0);
 assert.equal(report.summary.humanCurriculumReviewed,0);
 assert.ok(report.rows.every(r=>r.referenceActions>=1));
 assert.ok(report.rows.every(r=>r.referenceTurns>=1));
 assert.ok(report.rows.every(r=>r.proofKind!=="none"));
});
test("CSV exports complete review inventory with no source mutation, player save data or leaked runtime analytics",()=>{
 const report=structuralAudit();
 const csv=auditCsv(report);
 assert.equal(csv.split("\n").length,502,"header + 500 rows + trailing LF");
 assert.ok(csv.startsWith("id,index,galaxy,world"));
 assert.ok(csv.includes("humanCurriculumReview"));
 assert.ok(csv.includes("proofStatus"));
 assert.ok(csv.includes("empiricalDifficulty"));
 assert.ok(csv.includes(LEVELS[0].id));
 assert.ok(csv.includes(LEVELS.at(-1).id));
 const source=read("src/readiness-audit.js");
 assert.doesNotMatch(source,/localStorage|sessionStorage|navigator\.|fetch\(|XMLHttpRequest|Date\.now\(/);
 assert.match(read("scripts/run-readiness-audit.mjs"),/process\.exitCode=1/);
});
