test("steps 2 and 3 only display reducer-verifiable actions from THIS board and current position",()=>{
 for(const p of [LEVELS[0],LEVELS[1],LEARN_LEVELS[0],BONUS_TRIALS[0],LEVELS[250]]){
  const proof=p.revision===4?certifyRemix(p):solve(p,{maxStates:55000});
  assert.equal(proof.status,"solved",p.id);
  const start=initial(p);
  const route=continuationFromProof(p,start,proof);
  assert.ok(route,p.id+" reference must replay");
  assert.equal(replay(p,route.actions).ok,true,p.id);
  assert.match(hintInstruction(p,start,{status:"solved",...route},false),/verified next move/i);
  const reveal=hintInstruction(p,start,{status:"solved",...route},true);
  assert.match(reveal,/CURRENT position/);
  assert.match(reveal,/1\. /);
  assert.doesNotMatch(reveal,/globally optimal solution\./);
  const first=route.actions[0],after=reduce(p,start,first);
  assert.equal(after.ok,true,p.id);
  const suffix=continuationFromProof(p,after.state,proof);
  assert.ok(suffix,p.id+" state-specific suffix");
  assert.ok(validateHintRoute(p,after.state,suffix.actions));
 }
});
test("invalid historical proof, forged payment or unwinnable branch never leaks made-up solution",()=>{
 const p=LEVELS[0],state=initial(p);
 const forged={status:"solved",actions:[{type:"tap",id:"forged",color:"U"},{type:"cast"}]};
 assert.equal(continuationFromProof(p,state,forged),null);
 assert.equal(validateHintRoute(p,state,forged.actions),null);
 assert.match(hintInstruction(p,state,{status:"inconclusive",actions:[]},true),/No verified winning continuation/);
 const legal=legalContinuation(p,state,forged,{maxStates:1000});
 assert.equal(legal.status,"solved");
 assert.ok(validateHintRoute(p,state,legal.actions));
});
